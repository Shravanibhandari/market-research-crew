import re
import datetime
from xml.sax.saxutils import escape
import pandas as pd
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import mm
from reportlab.pdfgen import canvas
from reportlab.platypus import (SimpleDocTemplate, Paragraph, Spacer, Table,
                                TableStyle)

NAVY = colors.HexColor("#1F3A5F")
FOOTER_NOTE = "Generated by Multi-Agent Market Research Crew - for informational use only."


class NumberedCanvas(canvas.Canvas):
    """Canvas that prints 'Page X of Y' by collecting pages first."""

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved = []

    def showPage(self):
        self._saved.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        total = len(self._saved)
        for state in self._saved:
            self.__dict__.update(state)
            self.setFont("Helvetica", 8)
            self.setFillColor(colors.grey)
            self.drawString(20 * mm, 10 * mm, FOOTER_NOTE)
            self.drawRightString(190 * mm, 10 * mm,
                                 f"Page {self._pageNumber} of {total}")
            super().showPage()
        super().save()


def _inline(text: str) -> str:
    text = escape(text)
    return re.sub(r"\*\*(.+?)\*\*", r"<b>\1</b>", text)


def _markdown_to_flowables(md: str, styles):
    out = []
    for line in md.splitlines():
        s = line.strip()
        if not s or s.startswith("|") or set(s) <= set("-_* "):
            continue
        if s.startswith("### "):
            out.append(Paragraph(_inline(s[4:]), styles["h3"]))
        elif s.startswith("## "):
            out.append(Paragraph(_inline(s[3:]), styles["h2"]))
        elif s.startswith("# "):
            out.append(Paragraph(_inline(s[2:]), styles["h2"]))
        elif s[0] in "-*" and s[1:2] == " ":
            out.append(Paragraph(_inline(s[2:]), styles["bullet"], bulletText="•"))
        else:
            out.append(Paragraph(_inline(s), styles["body"]))
    return out


def build_pdf(report_md: str, summary_df: pd.DataFrame, output_path: str,
              title: str = "Market Research Report", query: str = "") -> str:
    base = getSampleStyleSheet()
    styles = {
        "body": ParagraphStyle("body", parent=base["BodyText"], leading=15, spaceAfter=6),
        "h2": ParagraphStyle("h2", parent=base["Heading2"], textColor=NAVY, spaceBefore=12),
        "h3": ParagraphStyle("h3", parent=base["Heading3"], textColor=NAVY),
        "bullet": ParagraphStyle("bullet", parent=base["BodyText"], leftIndent=14, leading=15),
    }
    doc = SimpleDocTemplate(output_path, pagesize=A4, leftMargin=20 * mm,
                            rightMargin=20 * mm, topMargin=18 * mm,
                            bottomMargin=20 * mm, title=title, author="Market Research Crew")
    banner = Table(
        [[Paragraph(f"<font color='white' size='18'><b>{escape(title)}</b></font>", base["Normal"])],
         [Paragraph(f"<font color='white' size='9'>Query: {escape(query)} &nbsp;|&nbsp; "
                    f"Date: {datetime.date.today():%d %b %Y}</font>", base["Normal"])]],
        colWidths=[170 * mm])
    banner.setStyle(TableStyle([("BACKGROUND", (0, 0), (-1, -1), NAVY),
                                ("LEFTPADDING", (0, 0), (-1, -1), 10),
                                ("TOPPADDING", (0, 0), (-1, -1), 8),
                                ("BOTTOMPADDING", (0, 0), (-1, -1), 8)]))
    story = [banner, Spacer(1, 12)]
    story += _markdown_to_flowables(report_md, styles)

    story += [Spacer(1, 10), Paragraph("Summary Statistics", styles["h2"])]
    df = summary_df.round(2).reset_index().rename(columns={"index": "stat"})
    data = [list(map(str, df.columns))] + df.astype(str).values.tolist()
    table = Table(data, repeatRows=1)
    table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), NAVY), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"), ("FONTSIZE", (0, 0), (-1, -1), 8),
        ("GRID", (0, 0), (-1, -1), 0.4, colors.grey),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#EEF2F7")]),
        ("ALIGN", (1, 0), (-1, -1), "CENTER")]))
    story.append(table)
    doc.build(story, canvasmaker=NumberedCanvas)
    return output_path
